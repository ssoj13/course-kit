/**
 * Course links, resolved at build time so a renamed lesson or term breaks the build instead of a page:
 *   lesson:<slug>[#anchor] -> <base><lang>/<module>/<slug>/[#anchor]
 *   page:<name>[#anchor]   -> <base><lang>/<path>/            (engine pages + the course's own `pages` option)
 *   term:<id>              -> <base><lang>/glossary/#term-<id>
 * `<lang>` is empty for the default language and `/<code>` for the others: a link always stays in the language of
 * the page it is on. Used by the Markdown plugin below, by the Starlight route middleware (hero action links in
 * frontmatter) and by components (also in the browser bundle, hence no Node imports). Plain ESM like data.mjs.
 */

/** Pages every course has (generated by the engine). */
export const ENGINE_PAGES = { home: '', roadmap: 'roadmap', glossary: 'glossary' };

/** Anchor id of a term on the glossary page. */
export const termAnchor = (/** @type {string} */ id) => `term-${id}`;

/**
 * Builds a resolver bound to one course and one language.
 * @param {import('./data.mjs').CourseJson} course
 * @param {import('./data.mjs').TermsJson} terms
 * @param {Record<string, string>} pages extra page name -> path below the base (course-specific docs pages)
 * @param {string} base site base path, e.g. `/vulkan-course`
 * @param {string} [prefix] language prefix: '' for the default language, `/ru` for Russian
 */
export function makeResolver(course, terms, pages, base, prefix = '') {
	const root = base.replace(/\/$/, '') + prefix;
	/** @type {Map<string, string>} */
	const lessons = new Map(course.modules.flatMap((m) => m.lessons.map((l) => [l.slug, `${m.slug}/${l.slug}`])));
	/** @type {Map<string, string>} */
	const pageMap = new Map(Object.entries({ ...ENGINE_PAGES, ...pages }));
	const termIds = new Set(terms.terms.map((t) => t.id));

	/**
	 * Resolves a course URL; returns null for any other URL (http:, relative, #anchor).
	 * @param {string} url
	 * @param {string} [where] file name for error messages
	 * @returns {string | null}
	 */
	return function resolve(url, where = 'unknown file') {
		const m = /^(lesson|page|term):([^#]*)(#.*)?$/.exec(url);
		if (!m) return null;
		const [, scheme, name, hash = ''] = m;
		if (scheme === 'term') {
			if (!termIds.has(name)) throw new Error(`${where}: unknown term "${name}" in "${url}" (add it to terms.json)`);
			if (hash) throw new Error(`${where}: "${url}": term links take no #anchor`);
			return `${root}/glossary/#${termAnchor(name)}`;
		}
		const table = scheme === 'lesson' ? lessons : pageMap;
		const path = table.get(name);
		if (path === undefined) {
			throw new Error(`${where}: unknown course link "${scheme}:${name}" (known: ${[...table.keys()].join(', ')})`);
		}
		return `${root}/${path ? `${path}/` : ''}${hash}`;
	};
}

/**
 * Language of a docs file from its path: `.../content/docs/<code>/...` for a non-default language, else the default.
 * @param {string} path file path or file URL
 * @param {readonly string[]} others non-default language codes
 * @param {string} fallback default language code
 */
export function langOfFile(path, others, fallback) {
	const m = /[\\/]content[\\/]docs[\\/]([^\\/]+)[\\/]/.exec(decodeURIComponent(path));
	return m && others.includes(m[1]) ? m[1] : fallback;
}

/**
 * Sätteri mdast plugin (Astro 7's Markdown/MDX processor): rewrites course links in Markdown links and link
 * definitions, in the language of the file. JSX `href`s are not touched; components resolve through lib/course.ts.
 * @param {Record<string, (url: string, where?: string) => string | null>} resolvers per language code
 * @param {string} fallback default language code
 */
export function courseLinksPlugin(resolvers, fallback) {
	const others = Object.keys(resolvers).filter((c) => c !== fallback);
	/** @param {{ url: string }} node @param {any} ctx */
	const rewrite = (node, ctx) => {
		const where = ctx.fileURL ? String(ctx.fileURL) : undefined;
		const lang = where ? langOfFile(where, others, fallback) : fallback;
		const next = resolvers[lang](node.url, where);
		if (next) ctx.setProperty(node, 'url', next);
	};
	return { name: 'course-links', link: rewrite, definition: rewrite };
}
